// Builds syntaxes/flisp.tmLanguage.json from syntaxes/flisp.tmLanguage.template.json
// by inserting the mnemonic lists from src/mnemonics.js.
//
//   node scripts/build-grammar.js          write the grammar
//   node scripts/build-grammar.js --check  only check that the grammar is up to date (used by npm test)

const fs = require('fs');
const path = require('path');
const lists = require('../src/mnemonics');

const ROOT = path.join(__dirname, '..');
const TEMPLATE = path.join(ROOT, 'syntaxes', 'flisp.tmLanguage.template.json');
const OUTPUT = path.join(ROOT, 'syntaxes', 'flisp.tmLanguage.json');

const NOTE = 'GENERATED from flisp.tmLanguage.template.json and src/mnemonics.js by scripts/build-grammar.js - ' +
  'do not edit this file; edit the template or the lists and run npm run build:grammar.';

function build() {
  const template = fs.readFileSync(TEMPLATE, 'utf8');
  const values = {
    GENERATED_NOTE: NOTE,
    ALL: lists.ALL,
    INHERENT_FLOW: lists.INHERENT_FLOW,
    INHERENT: lists.INHERENT,
    FLOW: lists.FLOW,
    DIRECTIVES: lists.DIRECTIVES,
    LAB: lists.LAB,
    OPERAND_INSTRUCTIONS: lists.OPERAND_INSTRUCTIONS,
    REGISTERS: lists.REGISTERS,
  };
  const out = template.replace(/\{\{([A-Z_]+)\}\}/g, (m, key) => {
    if (!(key in values)) throw new Error(`Unknown placeholder ${m} in ${path.basename(TEMPLATE)}`);
    const v = values[key];
    return Array.isArray(v) ? v.join('|') : v;
  });
  JSON.parse(out); // fail early on broken JSON
  return out;
}

const generated = build();
const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
const same = current.replace(/\r\n/g, '\n') === generated.replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  if (!same) {
    console.log('FAIL  syntaxes/flisp.tmLanguage.json is out of date - run: npm run build:grammar');
    process.exit(1);
  }
  console.log('ok    syntaxes/flisp.tmLanguage.json is up to date with the template and src/mnemonics.js');
} else if (same) {
  console.log('syntaxes/flisp.tmLanguage.json is already up to date');
} else {
  fs.writeFileSync(OUTPUT, generated);
  console.log('wrote syntaxes/flisp.tmLanguage.json');
}
